package battleship;

/** Exemplo para PROVOCAR o cheiro Long Method num ramo de teste. Nao fazer merge no master. */
public class LongMethodSmell {
    public int demo() {
        int a = 1;
        int b = 2;
        int c = a + b;
        int d = c * 2;
        int e = d - a;
        int f = e + b;
        int g = f * c;
        int h = g - d;
        int i = h + e;
        int j = i * 2;
        int k = j - f;
        int l = k + g;
        int m = l * 3;
        int n = m - h;
        int o = n + i;
        int p = o * 2;
        int q = p - j;
        int r = q + k;
        int s = r * 2;
        int t = s - l;
        int u = t + m;
        int v = u * 2;
        int w = v - n;
        int x = w + o;
        int y = x * 2;
        int z = y - p;
        a = z + 1;
        b = a + 2;
        c = b + 3;
        d = c + 4;
        e = d + 5;
        f = e + 6;
        g = f + 7;
        h = g + 8;
        i = h + 9;
        j = i + 10;
        return j;
    }
}
